function _esc(s){ return s.replace(/</g,'&lt;'); }
function genBoard(boardId, def){
  const out = [];
  for(let i=0;i<def.count;i++){
    const title = def.pre ? def.pre()+def.subj() : (def.tag ? `【${def.tag()}】${def.subj()}` : def.subj());
    const parts = def.body();
    const t = { id:'g_'+boardId+'_'+i, title:title, time:rt(), body:Array.isArray(parts) ? parts.join('\n\n') : parts };
    /* 作者：PERSONAS 驱动（pool 版块）或机构口吻（notice 等保留 au/lv） */
    if(def.pool){ const p = pk(def.pool); t.author = p.name + ' · ' + p.role; t.lv = p.lv; }
    else { t.author = def.au(); t.lv = def.lv(); }
    if(boardId!=='vault') t.body = _esc(t.body);
    if(def.repBody && _R()<0.30){          // ~30% 概率挂 1–4 条回复（作者同出 PERSONAS）
      const n = ri(1,4); t.replies = [];
      const rp = def.repPool || PERSONAS;
      let last = t.time;
      for(let k=0;k<n;k++){
        const p = pk(rp);
        let rb = pk(def.repBody);
        if(_R()<0.18) rb += pk([' 以上。',' 补充完毕。',' 就这样。',' 再啰嗦一句：注意自检。',' 不多说了，值班去了。']);
        last = rtAfter(last);
        t.replies.push({ author:p.name + ' · ' + p.role, lv:p.lv, time:last,
          body:boardId==='vault' ? rb : _esc(rb) });
      }
    }
    out.push(t);
  }
  return out;
}

